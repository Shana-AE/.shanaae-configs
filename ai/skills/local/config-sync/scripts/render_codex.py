#!/usr/bin/env python3
"""Render Codex portable-core artifacts from the opencode source.

Generated into ``.codex/``:
  agents/*.toml          <- .config/opencode/agents/*.md   (subagents)
  prompts/*.md           <- .config/opencode/{command,commands}/*.md
  qiniu.config.toml      <- a selectable provider profile (cc-switch proxy)

Usage:
  python3 render_codex.py            # write
  python3 render_codex.py --check    # exit 1 on drift
  python3 render_codex.py --dry-run  # print, write nothing
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parents[4]
OPENCODE_DIR = REPO_ROOT / ".config" / "opencode"
AGENTS_SRC = OPENCODE_DIR / "agents"
PROMPTS_SRC = [OPENCODE_DIR / "command", OPENCODE_DIR / "commands"]
CODEX_DIR = REPO_ROOT / ".codex"
CODEX_AGENTS = CODEX_DIR / "agents"
CODEX_PROMPTS = CODEX_DIR / "prompts"
QINIU_PROFILE = CODEX_DIR / "qiniu.config.toml"

# Codex sandbox per agent role (read-only unless it must write).
SANDBOX = {
    "english-tutor": "read-only",
    "image-op": "workspace-write",
    "image-op-pro": "workspace-write",
    "lark": "workspace-write",
    "web-devtools": "workspace-write",
    "windows-use": "workspace-write",
}

# Prompts to skip (no Codex equivalent).
SKIP_PROMPTS = {"tokenscope"}

QINIU_BASE_URL = "http://127.0.0.1:15721/v1"
QINIU_DEFAULT_MODEL = "deepseek/deepseek-v4-pro"


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Lenient frontmatter parse: opencode descriptions contain raw colons and
    folded (``>-``) blocks that strict YAML rejects."""
    if not text.startswith("---"):
        return {}, text
    end = text.index("\n---", 3)
    fm = text[3:end]
    body = text[end + 4 :].lstrip("\n")
    meta: dict[str, str] = {}
    lines = fm.split("\n")
    i = 0
    while i < len(lines):
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):\s?(.*)$", lines[i])
        if not match:
            i += 1
            continue
        key, value = match.group(1), match.group(2).strip()
        if value in (">-", ">", "|", "|-"):
            block: list[str] = []
            i += 1
            while i < len(lines) and (lines[i].startswith((" ", "\t")) or not lines[i].strip()):
                if lines[i].strip():
                    block.append(lines[i].strip())
                i += 1
            meta[key] = " ".join(block)
            continue
        meta[key] = value
        i += 1
    return meta, body


def toml_str(value: str) -> str:
    """Single-line TOML basic string."""
    value = re.sub(r"\s+", " ", value).strip()
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def toml_multiline(value: str) -> str:
    value = value.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return '"""\n' + value.rstrip() + '\n"""'


def render_agent(path: Path) -> tuple[str, str]:
    meta, body = parse_frontmatter(path.read_text(encoding="utf-8"))
    name = path.stem
    lines = [
        f"# Generated by config-sync from .config/opencode/agents/{path.name} — do not edit.",
        f"name = {toml_str(name)}",
        f"description = {toml_str(meta.get('description', name))}",
    ]
    model = meta.get("model")
    if model and "/" in model:
        provider, model_id = model.split("/", 1)
        lines.append(f"model = {toml_str(model_id)}")
        lines.append(f"model_provider = {toml_str(provider)}")
    sandbox = SANDBOX.get(name)
    if sandbox:
        lines.append(f"sandbox_mode = {toml_str(sandbox)}")
    lines.append(f"developer_instructions = {toml_multiline(body)}")
    return f"{name}.toml", "\n".join(lines) + "\n"


def render_prompt(path: Path) -> tuple[str, str] | None:
    if path.stem in SKIP_PROMPTS:
        return None
    meta, body = parse_frontmatter(path.read_text(encoding="utf-8"))
    desc = meta.get("description") or f"Custom prompt: {path.stem}"
    front = f"---\ndescription: {desc}\n---\n\n"
    return f"{path.stem}.md", front + body.rstrip() + "\n"


def render_qiniu_profile() -> str:
    return f"""# Generated by config-sync — select with: codex --profile qiniu
# Routes through cc-switch's local Responses->Chat proxy (Qiniu speaks only
# Chat Completions). Start cc-switch with local routing enabled first.
model_provider = "qiniu"
model = "{QINIU_DEFAULT_MODEL}"
model_reasoning_effort = "high"

[model_providers.qiniu]
name = "Qiniu AI (via cc-switch proxy)"
base_url = "{QINIU_BASE_URL}"
wire_api = "responses"
env_key = "QINIU_AI_API_KEY"
"""


def build() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for path in sorted(AGENTS_SRC.glob("*.md")):
        fname, content = render_agent(path)
        out[CODEX_AGENTS / fname] = content
    seen: set[str] = set()
    for src in PROMPTS_SRC:
        if not src.is_dir():
            continue
        for path in sorted(src.glob("*.md")):
            rendered = render_prompt(path)
            if not rendered:
                continue
            fname, content = rendered
            if fname in seen:
                continue
            seen.add(fname)
            out[CODEX_PROMPTS / fname] = content
    out[QINIU_PROFILE] = render_qiniu_profile()
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    files = build()
    stale: list[str] = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(str(path.relative_to(REPO_ROOT)))
        if args.dry_run:
            print(f"===== {path.relative_to(REPO_ROOT)} =====")
            print(content)
        elif not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if args.check:
        if stale:
            print("STALE Codex artifacts (run render_codex.py):", file=sys.stderr)
            for s in stale:
                print(f"  {s}", file=sys.stderr)
            return 1
        print("ok: Codex artifacts in sync")
        return 0
    if not args.dry_run:
        print(f"wrote {len(files)} file(s): {', '.join(sorted(str(p.relative_to(REPO_ROOT)) for p in files))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
