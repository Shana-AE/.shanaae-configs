#!/usr/bin/env python3
"""Merge the portable Codex config into the machine-local Windows Codex home.

The Codex desktop app reads ``C:\\Users\\<user>\\.codex\\config.toml`` (the
WSL backend only affects where shell/tools run). This script:

  1. merges the canonical ``[mcp_servers.*]`` block (same tolerant sentinel
     merge as ``mcp-sync``, preserving app-owned tables) into the Windows
     ``config.toml``;
  2. copies the generated ``.codex/agents/*.toml`` and ``.codex/prompts/*.md``
     into the Windows home (only files carrying the config-sync header; foreign
     files are left untouched).

Usage:
  python3 sync_codex_windows.py            # dry-run (diff + plan)
  python3 sync_codex_windows.py --apply    # write, with timestamped backups
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
import time
from difflib import unified_diff
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parents[4]
MCP_SCRIPTS = REPO_ROOT / "ai" / "skills" / "local" / "mcp-sync" / "scripts"
sys.path.insert(0, str(MCP_SCRIPTS))
import sync_mcp  # noqa: E402

GENERATED_HEADER = "Generated by config-sync"


def find_windows_codex_home() -> Path | None:
    env = os.environ.get("CODEX_WINDOWS_HOME")
    if env:
        return Path(env)
    mnt = Path("/mnt/c/Users")
    if mnt.is_dir():
        for user in sorted(p.name for p in mnt.iterdir() if p.is_dir()):
            cand = mnt / user / ".codex"
            if (cand / "config.toml").exists():
                return cand
    return None


def backup(path: Path) -> Path:
    stamp = time.strftime("%Y%m%dT%H%M%S")
    dest = path.with_name(f"{path.name}.bak.{stamp}")
    shutil.copy2(path, dest)
    return dest


def merge_config(win_home: Path, apply: bool) -> bool:
    config = win_home / "config.toml"
    sync_mcp.CODEX_CONFIG = str(config)
    ordered, excludes = sync_mcp.load_canonical()
    new_text = sync_mcp.render_codex(ordered, excludes["codex"])
    old_text = config.read_text(encoding="utf-8") if config.exists() else ""
    if old_text == new_text:
        print(f"  [config] {config} already in sync")
        return False
    diff = unified_diff(
        old_text.splitlines(keepends=True),
        new_text.splitlines(keepends=True),
        fromfile="current",
        tofile="target",
        n=1,
    )
    sys.stdout.write("  [config] DRIFT:\n" + sync_mcp.redact("".join(diff)))
    if apply:
        if config.exists():
            bak = backup(config)
            print(f"  [config] backup: {bak}")
        config.write_text(new_text, encoding="utf-8")
        print(f"  [config] written: {config}")
    return True


def copy_generated(src_dir: Path, dst_dir: Path, apply: bool, require_header: bool = True) -> bool:
    if not src_dir.is_dir():
        return False
    changed = False
    for src in sorted(src_dir.iterdir()):
        if not src.is_file():
            continue
        if require_header:
            head = src.read_text(encoding="utf-8")[:200]
            if GENERATED_HEADER not in head:
                continue
        dst = dst_dir / src.name
        old = dst.read_text(encoding="utf-8") if dst.exists() else None
        new = src.read_text(encoding="utf-8")
        if old == new:
            continue
        changed = True
        print(f"  [{dst_dir.name}] {dst.name}: {'update' if old is not None else 'create'}")
        if apply:
            dst_dir.mkdir(parents=True, exist_ok=True)
            if dst.exists():
                backup(dst)
            dst.write_text(new, encoding="utf-8")
    return changed


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--apply", action="store_true", help="write changes (default dry-run)")
    args = ap.parse_args()

    win_home = find_windows_codex_home()
    if not win_home:
        print("Windows Codex home not found (set CODEX_WINDOWS_HOME) — nothing to do.")
        return 0

    print(f"== sync-codex-windows ({'APPLY' if args.apply else 'DRY-RUN'}) ==")
    print(f"   target: {win_home}")
    changed = merge_config(win_home, args.apply)
    changed |= copy_generated(REPO_ROOT / ".codex" / "agents", win_home / "agents", args.apply)
    changed |= copy_generated(REPO_ROOT / ".codex" / "prompts", win_home / "prompts", args.apply, require_header=False)

    if not changed:
        print("Already in sync.")
    elif not args.apply:
        print("\n(dry-run only. Run with --apply to write.)")
    else:
        print("\nDone. Restart the Codex app to pick up changes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
